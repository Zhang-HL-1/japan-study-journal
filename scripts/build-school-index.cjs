const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
function build(exams,papers,map){
 const unique=values=>[...new Set(values.filter(Boolean))];
 const count=rows=>({records:rows.length,general:rows.filter(r=>r.admissionType==='general').length,international:rows.filter(r=>r.admissionType==='international'||r.internationalGeneral===true).length});
 return {version:1,regions:map.regions,schools:exams.universities.map(u=>{
  const records=exams.records.filter(r=>r.universityId===u.id),ps=papers.papers.filter(p=>p.universityId===u.id),campuses=map.campuses.filter(c=>c.universityId===u.id);
  const dates=unique(records.map(r=>r.verifiedAt)).sort();
  const graduates=unique([...records.map(r=>r.graduateSchool),...ps.map(p=>p.graduateSchool),...campuses.flatMap(c=>c.units.map(g=>g.graduateSchool))]);
  return {...u,...count(records),papers:ps.length,pdfs:unique(ps.flatMap(p=>p.files.map(f=>f.url))).length,verifiedFrom:dates[0]||'',verifiedTo:dates.at(-1)||'',regions:unique(campuses.map(c=>c.region)),
   campuses:campuses.map(c=>({id:c.id,name:c.name,prefecture:c.prefecture,city:c.city,graduates:unique(c.units.map(g=>g.graduateSchool))})),
   graduates:graduates.map(name=>{
    const rs=records.filter(r=>r.graduateSchool===name),pp=ps.filter(p=>p.graduateSchool===name);
    return {name,...count(rs),papers:pp.length,campuses:campuses.filter(c=>c.units.some(g=>g.graduateSchool===name)).length};
   })};
 })};
}
function serialize(data){return '/* Generated by scripts/build-school-index.cjs; do not edit by hand. */\n(function(root){const data='+JSON.stringify(data)+';if(typeof module!=="undefined"&&module.exports)module.exports=data;else root.SCHOOL_HUB_DATA=data;})(typeof globalThis!=="undefined"?globalThis:this);\n';}
if(require.main===module){
 const output=serialize(build(require('../exam-scope-data.js'),require('../past-papers-data.js'),require('../campus-map-data.js')));
 const target=path.join(root,'school-hub-data.js');
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){console.error('School index is stale. Run node scripts/build-school-index.cjs');process.exitCode=1;}}
 else{fs.writeFileSync(target,output);console.log('Generated school-hub-data.js ('+Buffer.byteLength(output)+' bytes)');}
}
module.exports={build,serialize};
