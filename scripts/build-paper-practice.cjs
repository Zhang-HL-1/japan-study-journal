function subjectsOf(labels){
 const text=labels.join(' / ').normalize('NFKC');
 const known=subjectRules.filter(([,re])=>re.test(text)).map(([s])=>s);
 if(/数学|数[1-3]|解析|代数|幾何/.test(text)&&!known.some(s=>['微积分','线性代数','微分方程','概率与统计','离散数学'].includes(s)))known.push('数学（综合）');
 if(/物理|力学|物[1-3]/.test(text)&&!known.some(s=>/力学|光学|电磁学|物理/.test(s)))known.push('物理（综合）');
 return known.length?[...new Set(known)]:['科目待细分'];
}
function build(data=catalog,schools=universities){
 return data.papers.filter(p=>p.files.some(f=>f.kind==='question')).map(p=>{
  const school=schools.find(s=>s.id===p.universityId);if(!school)throw Error('Unknown school '+p.id);
  const files=p.files.map(f=>{if(!core.fileURL(f))throw Error('Invalid file '+p.id);return {...Object.fromEntries(['label','kind','url','originalName','pages','startPage','endPage','answerProvenance'].filter(k=>f[k]!==undefined).map(k=>[k,f[k]])),subjects:subjectsOf([f.label])};});
  const subjects=subjectsOf(p.subjects||[]),year=core.yearOf(p);
  return {id:'paper:'+p.id,type:'paper',subject:subjects[0],subjects,chapter:'原卷练习',difficulty:'未标注',title:p.title,
   prompt:'按整套原卷练习，公式、图表和日文题干以 PDF 原件为准。合卷包含多个科目，尚未逐题拆分。',
   answerText:'',explanation:[],hint:'请先独立作答；完成标记不代表答对，不计入正确率。',
   provenance:{kind:'exam',school:school.name,graduate:p.graduateSchool,major:p.department||'专攻未标注',year:p.originalYear||String(year),label:p.selectionName},
   paper:{catalogId:p.id,schoolId:p.universityId,year,yearBasis:p.yearBasis||'exam',examDates:p.examDates||[],originalSubjects:p.subjects||[],sourceNote:p.sourceNote||'',completeness:p.completeness||'',files},
   searchTerms:[...(school.aliases||[]),...(p.subjects||[]),...files.map(f=>f.label)].join(' ')};
 }).sort((a,b)=>b.paper.year-a.paper.year||a.provenance.school.localeCompare(b.provenance.school,'ja')||a.id.localeCompare(b.id));
}
function serialize(bank){return '/* Generated by scripts/build-paper-practice.cjs. Whole papers, not individual questions. */\n(function(root){const bank='+JSON.stringify(bank)+';if(typeof module!=="undefined"&&module.exports)module.exports=bank;else root.PAPER_PRACTICE_BANK=bank;})(typeof window!=="undefined"?window:globalThis);\n';}
if(require.main===module){const dest=path.join(__dirname,'../paper-practice-data.js'),text=serialize(build());if(process.argv.includes('--check')){if(fs.readFileSync(dest,'utf8')!==text)throw Error('Run node scripts/build-paper-practice.cjs');}else fs.writeFileSync(dest,text);console.log('Paper practice:',build().length,'catalog sets');}
module.exports={build,serialize,subjectsOf};
